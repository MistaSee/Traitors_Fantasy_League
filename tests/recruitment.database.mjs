const {PGlite}=await import(process.env.PGLITE_MODULE||'@electric-sql/pglite');
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=name=>readFileSync(new URL('../'+name,import.meta.url),'utf8');
const db=new PGlite();
await db.exec(`create role anon;create role authenticated;create schema auth;
create function auth.jwt() returns jsonb language sql as $$select '{}'::jsonb$$;
create function auth.uid() returns uuid language sql as $$select null::uuid$$;`);
await db.exec(read('schema.sql'));
const state=JSON.parse(read('web/seed.json'));
const recruitment=state.rules.pop();
state.preseasonLocked=true;state.episodes[2].locked=true;
state.episodes[2].counts={'4':{TALKING_HEAD:2}};state.rules[0].points=7;
await db.query('insert into public.league_config(id,state) values(1,$1)',[state]);
const before=(await db.query('select * from public.league_config')).rows[0];
await db.exec(read('migrations/20261002_recruitment_scoring.sql'));
const after=(await db.query('select * from public.league_config')).rows[0];
assert.deepEqual(after,{...before,revision:before.revision+1,state:{...state,rules:[...state.rules,recruitment]}});
await db.exec(read('migrations/20261002_recruitment_scoring.sql'));
assert.deepEqual((await db.query('select * from public.league_config')).rows[0],after);
await db.close();console.log('Recruitment upgrade preserves locked state and custom values; repeat run is unchanged.');
